"""Builds the slim icon kit (public/icons.css + subset fonts) from the full
Font Awesome kit in public/icons-local.css, keeping only icons the site uses.
Re-run after adding a new fa-* icon:  python3 scripts/build-icons.py
(needs: pip install fonttools brotli)"""
import re, pathlib, subprocess, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
FULL = (ROOT / "public/icons-local.css").read_text()

used = set()
for folder in ["src", "public/js"]:
    for f in (ROOT / folder).rglob("*"):
        if f.suffix in {".html", ".js", ".ts", ".tsx", ".json"} and f.is_file():
            used |= set(re.findall(r"\bfa-[a-z0-9-]+", f.read_text(errors="ignore")))

def blocks(css):
    i, n, out = 0, len(css), []
    while i < n:
        j = css.find("{", i)
        if j < 0: break
        depth, k = 1, j + 1
        while depth and k < n:
            if css[k] == "{": depth += 1
            elif css[k] == "}": depth -= 1
            k += 1
        out.append((css[i:j].strip(), css[j + 1:k - 1]))
        i = k
    return out

GLYPH = re.compile(r"^\.(fa-[a-z0-9-]+)::?before$")
out, codepoints = [], set()
for sel, body in blocks(re.sub(r"/\*.*?\*/", "", FULL, flags=re.S)):
    if "bootstrap-icons" in body or "bi-" in sel:
        continue
    if sel.startswith("@font-face"):
        fam = re.search(r'font-family:\s*"([^"]+)"', body)
        if not fam or fam.group(1) not in ("Font Awesome 6 Free", "Font Awesome 6 Brands"):
            continue
        body = re.sub(r"/fonts/(fa-[a-z]+-\d+)\.woff2", r"/fonts/\1.sub.woff2", body)
        out.append(f"{sel}{{{body}}}")
        continue
    sels = [s.strip() for s in sel.split(",")]
    if sels and all(GLYPH.match(s) for s in sels):
        keep = [s for s in sels if GLYPH.match(s).group(1) in used]
        if not keep:
            continue
        for cp in re.findall(r'content:\s*"\\([0-9a-f]+)"', body):
            codepoints.add(int(cp, 16))
        out.append(f"{','.join(keep)}{{{body}}}")
        continue
    out.append(f"{sel}{{{body}}}")

header = "/* Font Awesome Free 6.5.0 (CC BY 4.0 / SIL OFL 1.1 / MIT) — slim build, generated by scripts/build-icons.py */\n"
(ROOT / "public/icons.css").write_text(header + "".join(out) + "\n")

unicodes = ",".join(f"U+{c:04X}" for c in sorted(codepoints))
for name in ["fa-solid-900", "fa-brands-400", "fa-regular-400"]:
    subprocess.run([sys.executable, "-m", "fontTools.subset", str(ROOT / f"public/fonts/{name}.woff2"),
                    f"--unicodes={unicodes}", "--flavor=woff2", "--layout-features=*", "--no-hinting",
                    f"--output-file={ROOT / f'public/fonts/{name}.sub.woff2'}"], check=True)
print(f"{len(used)} icon names, {len(codepoints)} glyphs")
